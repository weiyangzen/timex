export const LANGS = ["en", "zh"] as const;

export type Lang = (typeof LANGS)[number];

type DictValue = string | ((params?: Record<string, string | number>) => string);

export type Dictionary = Record<string, DictValue>;

export const DEFAULT_LANG: Lang = "en";

export function normalizeLang(value: string | null | undefined): Lang {
  return value === "zh" || value === "en" ? value : DEFAULT_LANG;
}

export function isLang(value: string | null | undefined): value is Lang {
  return value === "zh" || value === "en";
}

export function otherLang(lang: Lang): Lang {
  return lang === "zh" ? "en" : "zh";
}

export function localeForLang(lang: Lang): string {
  return lang === "zh" ? "zh-CN" : "en-US";
}

export function stripLangPrefix(pathname: string | null | undefined): string {
  if (!pathname) return "/discover";
  const parts = pathname.split("/");
  if (isLang(parts[1])) {
    const rest = `/${parts.slice(2).join("/")}`;
    return rest === "/" ? "/discover" : rest;
  }
  return pathname || "/discover";
}

export function langFromPathname(pathname: string | null | undefined): Lang {
  if (!pathname) return DEFAULT_LANG;
  return normalizeLang(pathname.split("/")[1]);
}

export function withLang(lang: Lang, href: string): string {
  if (!href.startsWith("/")) return href;
  if (href === "/") return `/${lang}`;
  const [path, query = ""] = href.split("?");
  const barePath = stripLangPrefix(path);
  return `/${lang}${barePath}${query ? `?${query}` : ""}`;
}

export function switchLangHref(currentPathname: string | null | undefined, nextLang: Lang, search = ""): string {
  return `${withLang(nextLang, stripLangPrefix(currentPathname || "/discover"))}${search}`;
}

export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

export function createTranslator(lang: Lang) {
  return (key: string, params?: Record<string, string | number>) => {
    const value = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
    if (typeof value === "function") return value(params);
    return interpolate(value, params);
  };
}

